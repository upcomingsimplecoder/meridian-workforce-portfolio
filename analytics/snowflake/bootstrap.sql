-- Dedicated synthetic portfolio database only; operator reviews and executes.
-- No production employee records, broad account grants or Enterprise RLS assumptions.
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS MERIDIAN_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS MERIDIAN_ANALYTICS.MERIDIAN_RAW;
CREATE WAREHOUSE IF NOT EXISTS MERIDIAN_XS WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 90;
CREATE STAGE IF NOT EXISTS MERIDIAN_ANALYTICS.MERIDIAN_RAW.MERIDIAN_EXPORTS
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') FILE_FORMAT = (TYPE = PARQUET);
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS MERIDIAN_LOADER;
CREATE ROLE IF NOT EXISTS MERIDIAN_TRANSFORM;
CREATE ROLE IF NOT EXISTS MERIDIAN_READ;
GRANT USAGE ON DATABASE MERIDIAN_ANALYTICS TO ROLE MERIDIAN_LOADER;
GRANT USAGE ON SCHEMA MERIDIAN_ANALYTICS.MERIDIAN_RAW TO ROLE MERIDIAN_LOADER;
GRANT CREATE TABLE ON SCHEMA MERIDIAN_ANALYTICS.MERIDIAN_RAW TO ROLE MERIDIAN_LOADER;
GRANT READ, WRITE ON STAGE MERIDIAN_ANALYTICS.MERIDIAN_RAW.MERIDIAN_EXPORTS TO ROLE MERIDIAN_LOADER;
GRANT USAGE ON DATABASE MERIDIAN_ANALYTICS TO ROLE MERIDIAN_TRANSFORM;
GRANT USAGE ON SCHEMA MERIDIAN_ANALYTICS.MERIDIAN_RAW TO ROLE MERIDIAN_TRANSFORM;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MERIDIAN_ANALYTICS.MERIDIAN_RAW TO ROLE MERIDIAN_TRANSFORM;
GRANT CREATE SCHEMA ON DATABASE MERIDIAN_ANALYTICS TO ROLE MERIDIAN_TRANSFORM;
GRANT USAGE ON DATABASE MERIDIAN_ANALYTICS TO ROLE MERIDIAN_READ;
GRANT USAGE ON WAREHOUSE MERIDIAN_XS TO ROLE MERIDIAN_LOADER;
GRANT USAGE ON WAREHOUSE MERIDIAN_XS TO ROLE MERIDIAN_TRANSFORM;
GRANT USAGE ON WAREHOUSE MERIDIAN_XS TO ROLE MERIDIAN_READ;
